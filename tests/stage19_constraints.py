"""Stage 19: pin constraints — write .const, read it back, project to .xdc, open in Robei.

Schema source: github.com/wwkkww1983/uart (prac_04_led), which ships both
``light_constrain.const`` and the ``light_constrain.xdc`` Robei generated from it.
The xdc comparison here is against that published output, line for line.
"""
from __future__ import annotations

import asyncio
import json
import pathlib
import shutil
import sys

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

ROOT = pathlib.Path(r"C:\dev\robei-mcp")
PYTHON = ROOT / ".venv" / "Scripts" / "python.exe"
WS = ROOT / "workspace"

results: list[tuple[str, bool]] = []

CODE = (
    "  assign led[0] = ~swt[0];\n"
    "  assign led[1] = swt[1] & ~swt[2];\n"
    "  assign led[3] = swt[2] & swt[3];\n"
    "  assign led[2] = (swt[1] & ~swt[2]) | (swt[2] & swt[3]);"
)
PINS = {"swt": ["G15", "P15", "W13", "T16"], "led": ["M14", "M15", "G14", "D18"]}

EXPECTED_XDC = """#This file is generated by Robei!
#Pin Assignment for Xilinx FPGA with Software Vivado.
set_property PACKAGE_PIN G15 [get_ports swt[0]]
set_property IOSTANDARD LVCMOS33 [get_ports swt[0]]
set_property PACKAGE_PIN P15 [get_ports swt[1]]
set_property IOSTANDARD LVCMOS33 [get_ports swt[1]]
set_property PACKAGE_PIN W13 [get_ports swt[2]]
set_property IOSTANDARD LVCMOS33 [get_ports swt[2]]
set_property PACKAGE_PIN T16 [get_ports swt[3]]
set_property IOSTANDARD LVCMOS33 [get_ports swt[3]]
set_property PACKAGE_PIN M14 [get_ports led[0]]
set_property IOSTANDARD LVCMOS33 [get_ports led[0]]
set_property PACKAGE_PIN M15 [get_ports led[1]]
set_property IOSTANDARD LVCMOS33 [get_ports led[1]]
set_property PACKAGE_PIN G14 [get_ports led[2]]
set_property IOSTANDARD LVCMOS33 [get_ports led[2]]
set_property PACKAGE_PIN D18 [get_ports led[3]]
set_property IOSTANDARD LVCMOS33 [get_ports led[3]]
"""


def payload(result) -> dict:
    if result.content and hasattr(result.content[0], "text"):
        try:
            return json.loads(result.content[0].text)
        except Exception:
            return {"raw": result.content[0].text[:400]}
    return {}


def check(name: str, ok: bool, data=None) -> None:
    results.append((name, ok))
    print(f"{'PASS' if ok else 'FAIL'}  {name}")
    if not ok and data is not None:
        print("      " + json.dumps(data, ensure_ascii=False)[:700])


async def main() -> int:
    params = StdioServerParameters(command=str(PYTHON), args=[str(ROOT / "server.py")], cwd=str(ROOT))
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            tools = {t.name: t for t in (await session.list_tools()).tools}
            print("TOOL_COUNT=", len(tools))
            for name in ("create_robei_const", "read_robei_const", "export_robei_xdc"):
                check(f"{name} registered", name in tools)
            check("read_robei_const is read-only", tools["read_robei_const"].annotations.read_only_hint is True)

            shutil.rmtree(WS / "const_demo", ignore_errors=True)
            proj = payload(await session.call_tool("create_robei_project", {"name": "const_demo", "models": []}))["proj"]
            model = payload(await session.call_tool("create_robei_model", {
                "proj_path": proj, "name": "light",
                "ports": [{"name": "swt", "direction": "input", "width": 4},
                          {"name": "led", "direction": "output", "width": 4}],
                "code": CODE}))
            check("light model created", model.get("ok") is True, model)

            created = payload(await session.call_tool("create_robei_const", {
                "proj_path": proj, "name": "light_constrain", "model": "light", "pins": PINS}))
            check("const created", created.get("ok") is True, created)
            check("const registered in .proj", created.get("registered_in_project") is True, created)

            const_path = WS / "const_demo" / "const" / "light_constrain.const"
            sha_before = created.get("sha256")
            read_back = payload(await session.call_tool("read_robei_const", {
                "path": "const_demo/const/light_constrain.const"}))
            check("const reads back as constrain", read_back.get("kind") == "constrain", read_back)
            got = {port: [bits[key] for key in sorted(bits, key=int)]
                   for port, bits in (read_back.get("pins") or {}).items()}
            check("bit->pin map round-trips", got == PINS, got)
            check("read did not modify the file", read_back.get("sha256") == sha_before, read_back.get("sha256"))

            xdc = payload(await session.call_tool("export_robei_xdc", {"proj_path": proj}))
            check("xdc exported", xdc.get("ok") is True, xdc)
            produced = const_path.parent.parent / "constrain" / "light_constrain.xdc"
            text = produced.read_text(encoding="utf-8") if produced.is_file() else ""
            check("xdc matches the published Robei output", text == EXPECTED_XDC,
                  {"got": text[:200], "want": EXPECTED_XDC[:200]})

            bad = payload(await session.call_tool("create_robei_const", {
                "proj_path": proj, "name": "bad1", "model": "light",
                "pins": {"swt": ["G15"], "led": ["M14", "M15", "G14", "D18"]}}))
            check("wrong pin count rejected", bad.get("code") == "invalid_argument", bad)
            bad = payload(await session.call_tool("create_robei_const", {
                "proj_path": proj, "name": "bad2", "model": "light",
                "pins": {**PINS, "ghost": ["A1"]}}))
            check("unknown port rejected", bad.get("code") == "invalid_argument", bad)
            bad = payload(await session.call_tool("create_robei_const", {
                "proj_path": proj, "name": "bad3", "model": "light",
                "pins": {"swt": ["G15", "P15", "W13", "not a pin"], "led": PINS["led"]}}))
            check("bad pin name rejected", bad.get("code") == "invalid_argument", bad)
            again = payload(await session.call_tool("create_robei_const", {
                "proj_path": proj, "name": "light_constrain", "model": "light", "pins": PINS}))
            check("existing const needs overwrite", again.get("code") == "already_exists", again)

            # --- Robei itself must accept the file ------------------------------
            await session.call_tool("robei_gui_close", {})
            await session.call_tool("robei_gui_launch", {"wait_s": 45})
            opened = payload(await session.call_tool("robei_gui_open_project", {"proj_path": proj}))
            check("Robei opens the project", opened.get("ok") is True, opened)
            tree = payload(await session.call_tool("robei_gui_open_model", {
                "name": "light_constrain.const", "timeout_s": 60}))
            check("Robei opens the generated .const", tree.get("ok") is True and tree.get("active") == "light_constrain", tree)
            await session.call_tool("robei_gui_close", {})

    passed = sum(1 for _, ok in results if ok)
    print(f"\n--- summary ---\n{passed}/{len(results)} passed")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
